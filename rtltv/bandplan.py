def wavelength(f):
    """Длина волны λ = c / f, м."""
    return C / f if f > 0 else float("nan")


def fmt_wavelength(f):
    if f <= 0:
        return "—"
    lam = wavelength(f)
    if lam >= 1000:
        return f"{lam / 1000:.1f} км".replace(".", ",")
    if lam >= 1:
        return (f"{lam:.0f} м" if lam >= 10 else f"{lam:.2f} м").replace(".", ",")
    return f"{lam * 100:.0f} см" if lam >= 0.1 else f"{lam * 1000:.0f} мм"


def wave_class(f):
    """(класс, бытовое название, длины волн) для частоты f или None."""
    for f0, f1, name, common, lam in WAVE_CLASSES:
        if f0 <= f < f1:
            return name, common, lam
    return None


def at(f):
    """Все выделения, в которые попадает частота f (сначала самые узкие)."""
    hits = [a for a in ALLOCATIONS if a[0] <= f <= a[1]]
    return sorted(hits, key=lambda a: a[1] - a[0])


def visible(f0, f1):
    """Выделения, пересекающиеся с полосой [f0, f1]."""
    return [a for a in ALLOCATIONS if a[1] > f0 and a[0] < f1]


def lanes(items, key0=lambda a: a[0], key1=lambda a: a[1]):
    """Разложить пересекающиеся полосы по дорожкам (жадно): [(дорожка, элемент)]."""
    ends = []
    out = []
    for a in sorted(items, key=key0):
        for i, e in enumerate(ends):
            if key0(a) >= e:
                ends[i] = key1(a)
                out.append((i, a))
                break
        else:
            ends.append(key1(a))
            out.append((len(ends) - 1, a))
    return out


def describe(f):
    """Текст для подсказки: частота, длина волны, класс волн и кто занимает."""
    lines = [f"{f / 1e6:.4f} МГц".replace(".", ",") + f" · λ ≈ {fmt_wavelength(f)}"]
    wc = wave_class(f)
    if wc:
        lines.append(f"{wc[1]} — {wc[0]} волны ({wc[2]})")
    for a in at(f):
        lines.append(f"{a[3]} ({KINDS[a[4]][1]})")
    return "\n".join(lines)


def log_pos(f, f_lo, f_hi):
    """Положение частоты 0…1 на логарифмической шкале [f_lo, f_hi]."""
    f = min(max(f, f_lo), f_hi)
    return (math.log10(f) - math.log10(f_lo)) / (math.log10(f_hi) - math.log10(f_lo))


def log_freq(pos, f_lo, f_hi):
    pos = min(max(pos, 0.0), 1.0)
    return 10 ** (math.log10(f_lo) + pos * (math.log10(f_hi) - math.log10(f_lo)))
